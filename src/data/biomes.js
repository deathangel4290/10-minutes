export const BIOME_ORDER = ['forest', 'snow', 'volcano', 'crypt'];

export function biomeUnlocked(save, id) {
  const b = BIOMES[id];
  if (!b.unlockedBy) return true;
  return ((save.regions && save.regions[b.unlockedBy] && save.regions[b.unlockedBy].escapes) || 0) > 0;
}
